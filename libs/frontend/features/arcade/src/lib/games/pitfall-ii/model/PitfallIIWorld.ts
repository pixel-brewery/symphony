/** Complete fixed Atari2600 cavern geometry in logical pixels; no random or repeated-room generator. @public */
export const PitfallIIWorld: IPitfallIIWorld = Object.freeze({
  width: 1280,
  height: 1413,
  chamberWidth: 160,
  levelHeight: 45,
  surfaceY: 120,
  platforms: Object.freeze([
    ...FLOORS.flatMap((row, level) =>
      row.flatMap((shape, chamber) =>
        FLOOR_SHAPES[shape].map(([start, end]) =>
          Object.freeze({
            x: chamber * 160 + start,
            y: 120 + level * 45,
            width: end - start,
            height: 13,
          }),
        ),
      ),
    ),
    Object.freeze({ x: 0, y: 1380, width: 1280, height: 33 }),
  ]),
  walls: Object.freeze([
    Object.freeze({ x: -4, y: 0, width: 4, height: 1413 }),
    Object.freeze({ x: 1280, y: 0, width: 4, height: 1413 }),
    ...WALLS.flatMap((row, level) =>
      row.map((boundary) =>
        Object.freeze({
          x: boundary * 160 - 2,
          y: 120 + (level - 1) * 45 + 9,
          width: 4,
          height: 45,
        }),
      ),
    ),
  ]),
  ladders: Object.freeze(
    LADDERS.flatMap((row, level) =>
      row.map((chamber) =>
        Object.freeze({
          x: chamber * 160 + 76,
          y: 120 + level * 45,
          height: level === 26 ? 74 : 45,
        }),
      ),
    ),
  ),
  water: Object.freeze([
    Object.freeze({ x: 320, y: 174, width: 320, height: 36 }),
    Object.freeze({ x: 640, y: 219, width: 160, height: 81 }),
    Object.freeze({ x: 800, y: 219, width: 160, height: 36 }),
    Object.freeze({ x: 0, y: 1344, width: 1280, height: 36 }),
  ]),
  items: Object.freeze(
    ITEMS.map(([kind, x, y], index) => Object.freeze({ id: `${kind}-${index}`, kind, x, y })),
  ),
  checkpoints: Object.freeze(CHECKPOINTS.map(([x, y], id) => Object.freeze({ id, x, y }))),
  hazards: Object.freeze(HAZARDS.map(([kind, x, y], id) => Object.freeze({ id, kind, x, y }))),
});
