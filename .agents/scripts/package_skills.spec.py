#!/usr/bin/env python3
"""Regression coverage for portable skill archive bytes and checkout inputs."""

from __future__ import annotations

import io
import json
import shutil
import subprocess
import sys
import tempfile
import unittest
import zipfile
from pathlib import Path, PurePath
from unittest.mock import patch

from package_skills import archive_bytes


def windows_path_less_than(left: PurePath, right: PurePath) -> bool:
    """Model Windows' case-insensitive component comparison on any test host."""
    return tuple(part.lower() for part in left.parts) < tuple(part.lower() for part in right.parts)


class PortableSkillArchiveTests(unittest.TestCase):
    def test_inherited_base_is_bundled_with_resolvable_links_without_changing_sources(self) -> None:
        with tempfile.TemporaryDirectory(prefix="inherited archive ") as directory:
            root = Path(directory)
            derived = root / ".agents/skills/derived"
            base = root / ".agents/skills/architecture"
            (derived / "references").mkdir(parents=True)
            (base / "references/common").mkdir(parents=True)
            source = "---\nname: derived\ndescription: Derived fixture.\nmetadata:\n  inherits: architecture\n---\n\nRead [base](../architecture/SKILL.md).\n"
            (derived / "SKILL.md").write_text(source)
            (derived / "references/project.md").write_text("Apply [workflow](../../architecture/references/common/workflow.md).\n")
            (base / "SKILL.md").write_text("---\nname: architecture\ndescription: Base.\n---\n\nRead [workflow](references/common/workflow.md).\n")
            (base / "references/common/workflow.md").write_text("Preserve the local project rules.\n")
            provenance = {"source": "pixel-brewery/skills", "ref": "a" * 40, "sourceType": "github", "computedHash": "locked-base-content"}
            (root / "skills-lock.json").write_text(json.dumps({"version": 1, "skills": {"architecture": provenance, "unrelated": {"source": "other/repo"}}}))

            data = archive_bytes(derived)
            with zipfile.ZipFile(io.BytesIO(data)) as archive:
                names = archive.namelist()
                self.assertTrue(all(name.startswith("derived/") for name in names))
                self.assertIn("derived/dependencies/architecture/references/common/workflow.md", names)
                self.assertIn(b"[base](dependencies/architecture/SKILL.md)", archive.read("derived/SKILL.md"))
                self.assertIn(b"[workflow](../dependencies/architecture/references/common/workflow.md)", archive.read("derived/references/project.md"))
                self.assertIn(b"[workflow](references/common/workflow.md)", archive.read("derived/dependencies/architecture/SKILL.md"))
                self.assertEqual(json.loads(archive.read("derived/dependencies/skills-lock.json")), {"version": 1, "skills": {"architecture": provenance}})
            self.assertEqual((derived / "SKILL.md").read_text(), source)

            (base / "references/common/workflow.md").write_text("Updated shared foundation.\n")
            self.assertNotEqual(archive_bytes(derived), data)

    def test_missing_or_circular_bases_fail_packaging(self) -> None:
        with tempfile.TemporaryDirectory(prefix="invalid inherited archive ") as directory:
            root = Path(directory)
            derived = root / "derived"
            derived.mkdir()
            (derived / "SKILL.md").write_text("---\nname: derived\ndescription: Derived.\nmetadata:\n  inherits: architecture\n---\n\n# Workflow\n")
            with self.assertRaisesRegex(ValueError, "missing inherited skill architecture"):
                archive_bytes(derived)
            base = root / "architecture"
            base.mkdir()
            (base / "SKILL.md").write_text("---\nname: architecture\ndescription: Base.\nmetadata:\n  inherits: derived\n---\n\n# Workflow\n")
            with self.assertRaisesRegex(ValueError, "circular inherited skill"):
                archive_bytes(derived)

    def test_packaging_preserves_the_native_cli_lock(self) -> None:
        repository = Path(__file__).resolve().parents[2]
        with tempfile.TemporaryDirectory(prefix="portable lock ownership ") as directory:
            root = Path(directory)
            source = root / ".agents/skills/fixture-skill"
            (source / "agents").mkdir(parents=True)
            text = "---\nname: fixture-skill\ndescription: Portable fixture.\n---\n\n# Workflow\n"
            (source / "SKILL.md").write_text(text)
            (source / "agents/openai.yaml").write_text('interface:\n  default_prompt: "Use $fixture-skill."\n')
            mirror = root / ".claude/skills/fixture-skill/SKILL.md"
            mirror.parent.mkdir(parents=True)
            mirror.write_text(text + "\n<!-- Generated by .agents/scripts/sync_agent_configuration.py -->\n")
            native = '{"version":1,"skills":{"remote":{"source":"fixture/repo","ref":"' + "a" * 40 + '","sourceType":"github","computedHash":"preserve-me"}}}\n'
            (root / "skills-lock.json").write_text(native)

            result = subprocess.run([sys.executable, str(repository / ".agents/scripts/package_skills.py"), "--root", str(root)], capture_output=True, text=True)

            self.assertEqual(result.returncode, 0, result.stderr)
            self.assertEqual((root / "skills-lock.json").read_text(), native)
            portable = json.loads((root / ".agents/packages/skills-lock.json").read_text())
            self.assertEqual(portable["skills"][0]["name"], "fixture-skill")
            self.assertTrue((root / ".agents/packages/fixture-skill.skill").is_file())

    def test_unix_and_windows_builders_create_identical_bytes_and_metadata(self) -> None:
        # arrange
        with tempfile.TemporaryDirectory(prefix="portable skills ") as directory:
            skill = Path(directory) / "fixture-skill"
            (skill / "references").mkdir(parents=True)
            source = b"# Portable fixture\n\nRead [workflow](./references/workflow.md).\n"
            (skill / "SKILL.md").write_bytes(source)
            (skill / "references" / "workflow.md").write_bytes(b"Keep LF source bytes.\n")

            # act: exercise ZipInfo's real platform-dependent initialization.
            with patch("zipfile.sys.platform", "linux"):
                unix = archive_bytes(skill)
            with patch("zipfile.sys.platform", "win32"):
                windows = archive_bytes(skill)

        # assert: both the root directory and every file retain canonical metadata.
        self.assertEqual(windows, unix)
        with zipfile.ZipFile(io.BytesIO(windows)) as archive:
            self.assertEqual(len(archive.infolist()), 3)
            self.assertEqual(archive.read("fixture-skill/SKILL.md"), source)
            for entry in archive.infolist():
                self.assertEqual(entry.create_system, 3)
                self.assertEqual(entry.date_time, (1980, 1, 1, 0, 0, 0))
                self.assertEqual(entry.external_attr, (0o755 if entry.is_dir() else 0o644) << 16)

    def test_archive_order_uses_case_sensitive_components_on_windows(self) -> None:
        # arrange: uppercase names and directory prefixes distinguish both ordering pitfalls.
        with tempfile.TemporaryDirectory(prefix="skill path ordering ") as directory:
            skill = Path(directory) / "fixture-skill"
            files = ["SKILL.md", "agents/openai.yaml", "dir/workflow.md", "dir.md"]
            for relative in files:
                path = skill / relative
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(b"Portable source.\n")
            native = archive_bytes(skill)

            # act: exercise the filesystem path comparator as well as ZipInfo's platform default.
            with patch("zipfile.sys.platform", "win32"), patch.object(PurePath, "__lt__", windows_path_less_than):
                windows = archive_bytes(skill)

        # assert: retain POSIX component ordering, including dir/file before dir.md.
        self.assertEqual(windows, native)
        with zipfile.ZipFile(io.BytesIO(windows)) as archive:
            self.assertEqual(archive.namelist(), ["fixture-skill/", *[f"fixture-skill/{name}" for name in files]])

    def test_existing_canonical_archive_does_not_change_on_windows(self) -> None:
        # arrange
        root = Path(__file__).resolve().parents[2]
        expected = (root / ".agents" / "packages" / "maintain-i18n.skill").read_bytes()

        # act
        with patch("zipfile.sys.platform", "win32"), patch.object(PurePath, "__lt__", windows_path_less_than):
            actual = archive_bytes(root / ".agents" / "skills" / "maintain-i18n")

        # assert
        self.assertEqual(actual, expected)

    def test_windows_style_git_checkout_keeps_lf_sources_and_binary_archives(self) -> None:
        # arrange: isolate all Git writes in a test-owned repository, without making a commit.
        root = Path(__file__).resolve().parents[2]
        git = shutil.which("git")
        if not git:
            self.fail("The checkout regression requires the repository Git toolchain.")
        with tempfile.TemporaryDirectory(prefix="skill checkout ") as directory:
            fixture = Path(directory)
            payloads = {
                fixture / ".agents" / "skills" / "fixture-skill" / "SKILL.md": b"# Skill source\n\nKeep deterministic input.\n",
                fixture / "src" / "example.ts": b"export const ready = true;\n",
                fixture / "settings.json": b'{ "enabled": true }\n',
                # Text-like bytes deliberately require the explicit binary rule to preserve CRLF.
                fixture / ".agents" / "packages" / "fixture-skill.skill": b"portable archive\r\n",
            }
            for path, payload in payloads.items():
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(payload)
            (fixture / ".gitattributes").write_bytes((root / ".gitattributes").read_bytes())
            command = [git, "-c", "core.autocrlf=true", "-c", "core.eol=crlf"]
            subprocess.run([*command, "init", "--quiet"], cwd=fixture, capture_output=True, check=True)
            subprocess.run([*command, "add", "."], cwd=fixture, capture_output=True, check=True)
            for path in payloads:
                path.unlink()

            # act: reconstruct the working tree with CRLF conversion explicitly enabled.
            subprocess.run(
                [*command, "checkout-index", "--all", "--force"], cwd=fixture, capture_output=True, check=True
            )

            # assert: formatted source, text package inputs and binary package bytes stay unchanged.
            for path, payload in payloads.items():
                with self.subTest(path=path.relative_to(fixture)):
                    self.assertEqual(path.read_bytes(), payload)


if __name__ == "__main__":
    unittest.main()
