#!/usr/bin/env python3
# .agents/scripts/sync_agent_configuration.py
"""Synchronize repository guidance across Codex, OpenCode, Claude Code, and portable skills."""

from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from agent_config_common import find_root as locate_root, parse_frontmatter, plugin_provided_skills

MARKER = "Generated by .agents/scripts/sync_agent_configuration.py"
WORKSPACE_VARIABLE = "${workspaceFolder}"
# MCP servers Claude Code already receives from a plugin enabled in .claude/settings.json.
# `nx configure-ai-agents` strips these from .mcp.json for the same reason.
CLAUDE_PLUGIN_MCP_SERVERS = {"nx@nx-claude-plugins": {"nx", "nx-mcp"}}


@dataclass(frozen=True)
class Guidance:
    kind: str
    source: Path
    source_id: str
    description: str
    body: str


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail when generated configuration is stale.")
    parser.add_argument("--root", type=Path, default=None, help="Repository root.")
    return parser.parse_args()


def find_root(explicit: Path | None) -> Path:
    return locate_root(explicit, ".agents")


def slug(value: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", value.lower()).strip("-")


def source_id(path: Path) -> str:
    stem = path.stem
    for suffix in (".instructions", ".prompt", ".agent"):
        if stem.endswith(suffix):
            stem = stem[: -len(suffix)]
    return slug(stem)


def discover_guidance(root: Path) -> list[Guidance]:
    directories = {
        "agents": root / ".github" / "agents",
        "instructions": root / ".github" / "instructions",
        "prompts": root / ".github" / "prompts",
        "rules": root / ".github" / "rules",
    }
    result: list[Guidance] = []
    for kind, directory in directories.items():
        for path in sorted(directory.glob("*.md")):
            metadata, body = parse_frontmatter(path.read_text(encoding="utf-8"))
            description = metadata.get("description")
            if not description:
                heading = next((line[2:].strip() for line in body.splitlines() if line.startswith("# ")), path.stem)
                description = f"Apply the repository {kind} guidance for {heading}."
            result.append(Guidance(kind, path, source_id(path), description, body.rstrip()))
    return result


def quote(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def wrapper_files(root: Path, guidance: list[Guidance]) -> dict[Path, str]:
    expected: dict[Path, str] = {}
    for item in guidance:
        name = f"{item.kind}-{item.source_id}"
        relative = item.source.relative_to(root).as_posix()
        description = (
            f"Select and apply {relative}. Use when work matches this repository guidance "
            f"or the user explicitly mentions {item.source_id}."
        )
        skill = (
            f"---\nname: {name}\ndescription: {quote(description)}\n---\n\n"
            f"<!-- {MARKER} -->\n\n# {item.kind.title()}: {item.source_id.replace('-', ' ').title()}\n\n"
            f"Read [{relative}](../../../{relative}) completely, then apply it to the current task. "
            "Resolve conflicts in favor of the nearest AGENTS.md and explicit user instructions.\n"
        )
        default_prompt = "Use $" + name + " for the applicable repository guidance."
        openai = (
            "interface:\n"
            f"  display_name: {quote(item.source_id.replace('-', ' ').title())}\n"
            f"  short_description: {quote(('Apply repository ' + item.kind + ' guidance')[:64])}\n"
            f"  default_prompt: {quote(default_prompt)}\n"
        )
        base = root / ".agents" / "skills" / name
        expected[base / "SKILL.md"] = skill
        expected[base / "agents" / "openai.yaml"] = openai
    return expected


def load_servers(root: Path) -> dict[str, dict[str, Any]]:
    data = json.loads((root / ".vscode" / "mcp.json").read_text(encoding="utf-8"))
    servers = data.get("servers")
    if not isinstance(servers, dict):
        raise ValueError(".vscode/mcp.json must contain a servers object")
    return servers


def toml(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, list):
        return "[ " + ", ".join(toml(item) for item in value) + " ]"
    raise TypeError(f"Unsupported TOML value: {value!r}")


def render_codex_config(servers: dict[str, dict[str, Any]]) -> str:
    lines = [f"# {MARKER}", 'personality = "friendly"', ""]
    for name, server in servers.items():
        table = f"mcp_servers.{json.dumps(name)}"
        lines.append(f"[{table}]")
        if "command" in server:
            lines.append(f"command = {toml(server['command'])}")
            args = ["." if str(arg) == WORKSPACE_VARIABLE else str(arg) for arg in server.get("args", [])]
            if args:
                lines.append(f"args = {toml(args)}")
            lines.append('cwd = "."')
        elif "url" in server:
            lines.append(f"url = {toml(server['url'])}")
        else:
            raise ValueError(f"MCP server {name!r} needs command or url")
        lines.extend(["enabled = true", ""])
    lines.extend(["[features]", "multi_agent = true", "", "[agents]", "max_concurrent_threads_per_session = 4", ""])
    return "\n".join(lines)


def render_opencode_config(servers: dict[str, dict[str, Any]]) -> str:
    entries: dict[str, dict[str, Any]] = {}
    for name, server in servers.items():
        if "command" in server:
            args = ["." if str(arg) == WORKSPACE_VARIABLE else str(arg) for arg in server.get("args", [])]
            entries[name] = {"type": "local", "command": [server["command"], *args], "enabled": True}
        else:
            entries[name] = {"type": "remote", "url": server["url"], "enabled": True}
    return json.dumps({"$schema": "https://opencode.ai/config.json", "mcp": entries}, indent=2) + "\n"


def plugin_provided_mcp_servers(root: Path) -> set[str]:
    """MCP servers Claude Code already loads from an enabled plugin, so .mcp.json must not repeat them."""
    try:
        settings = json.loads((root / ".claude" / "settings.json").read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return set()
    enabled = settings.get("enabledPlugins")
    if not isinstance(enabled, dict):
        return set()
    return {name for plugin, names in CLAUDE_PLUGIN_MCP_SERVERS.items() if enabled.get(plugin) for name in names}


def render_claude_mcp_config(servers: dict[str, dict[str, Any]], plugin_servers: set[str]) -> str:
    entries: dict[str, dict[str, Any]] = {}
    for name, server in servers.items():
        if name in plugin_servers:
            continue
        if "command" in server:
            args = ["." if str(arg) == WORKSPACE_VARIABLE else str(arg) for arg in server.get("args", [])]
            entries[name] = {"type": "stdio", "command": server["command"], "args": args}
        else:
            entries[name] = {"type": "http", "url": server["url"]}
    return json.dumps({"mcpServers": entries}, indent=2) + "\n"


def skill_sources(root: Path, wrappers: dict[Path, str]) -> dict[str, str]:
    """Map portable skill name to SKILL.md text: hand-written skills from disk, generated wrappers from memory."""
    sources: dict[str, str] = {}
    for path in sorted((root / ".agents" / "skills").glob("*/SKILL.md")):
        text = path.read_text(encoding="utf-8")
        if MARKER in text:
            continue
        sources[path.parent.name] = text
    for path, content in wrappers.items():
        if path.name == "SKILL.md":
            sources[path.parent.name] = content
    return sources


def claude_files(root: Path, guidance: list[Guidance], wrappers: dict[Path, str]) -> dict[Path, str]:
    expected: dict[Path, str] = {}
    plugin_skills = plugin_provided_skills(root)
    for name, text in skill_sources(root, wrappers).items():
        if name in plugin_skills:
            continue
        metadata, body = parse_frontmatter(text)
        description = metadata.get("description")
        if not description:
            raise ValueError(f".agents/skills/{name}/SKILL.md needs a description in its frontmatter")
        source = f".agents/skills/{name}/SKILL.md"
        expected[root / ".claude" / "skills" / name / "SKILL.md"] = (
            f"---\nname: {metadata.get('name', name)}\ndescription: {quote(description)}\n---\n\n"
            f"<!-- {MARKER} -->\n\n"
            f"Source: [{source}](../../../{source}). Relative `references/` and `scripts/` paths resolve there.\n\n"
            f"{body.strip()}\n"
        )
    for item in guidance:
        if item.kind == "agents":
            expected[root / ".claude" / "agents" / f"{item.source_id}.md"] = (
                f"---\nname: {item.source_id}\ndescription: {quote(item.description)}\n---\n\n"
                f"<!-- {MARKER} -->\n\n{item.body}\n"
            )
    return expected


def provider_files(root: Path, guidance: list[Guidance], servers: dict[str, dict[str, Any]]) -> dict[Path, str]:
    expected = {
        root / ".codex" / "config.toml": render_codex_config(servers),
        root / "opencode.json": render_opencode_config(servers),
        root / ".mcp.json": render_claude_mcp_config(servers, plugin_provided_mcp_servers(root)),
        root / ".opencode" / ".gitignore": "# Generated runtime data\nnode_modules/\n",
    }
    for item in guidance:
        if item.kind == "agents":
            escaped = item.body.replace('"""', '\\"\\"\\"')
            expected[root / ".codex" / "agents" / f"{item.source_id}.toml"] = (
                f"# {MARKER}\nname = {toml(item.source_id)}\ndescription = {toml(item.description)}\n"
                f'developer_instructions = """\n{escaped}\n"""\n'
            )
            expected[root / ".opencode" / "agents" / f"{item.source_id}.md"] = (
                f"---\ndescription: {item.description}\nmode: subagent\n---\n\n"
                f"<!-- {MARKER} -->\n\n{item.body}\n"
            )
        if item.kind == "prompts":
            expected[root / ".opencode" / "commands" / f"{item.source_id}.md"] = (
                f"---\ndescription: {item.description}\n---\n\n"
                f"<!-- {MARKER} -->\n\n{item.body}\n"
            )
    wrappers = wrapper_files(root, guidance)
    expected.update(wrappers)
    expected.update(claude_files(root, guidance, wrappers))
    return expected


def format_content(root: Path, path: Path, content: str) -> str:
    if path.suffix not in {".json", ".md", ".yaml", ".yml"}:
        return content
    result = subprocess.run(
        ["yarn", "prettier", "--stdin-filepath", str(path)],
        cwd=root,
        input=content,
        text=True,
        capture_output=True,
        check=False,
    )
    if result.returncode:
        raise RuntimeError(f"Prettier failed for {path}: {result.stderr.strip()}")
    return result.stdout


def opencode_skill_copies(root: Path) -> list[str]:
    """Skill directories under .opencode/skills, which `nx configure-ai-agents --agents opencode` recreates."""
    return sorted(path.parent.name for path in (root / ".opencode" / "skills").glob("*/SKILL.md"))


def tracked_in_git(root: Path, relative_path: str) -> bool:
    """True when git tracks files under the path. False when git is unavailable or the path is untracked."""
    try:
        result = subprocess.run(
            ["git", "ls-files", "--", relative_path], cwd=root, capture_output=True, text=True, check=False
        )
    except OSError:
        return False
    return result.returncode == 0 and bool(result.stdout.strip())


def prune_empty_directories(root: Path) -> None:
    for directory in (root / ".claude" / "skills", root / ".claude" / "agents"):
        if not directory.is_dir():
            continue
        for path in sorted(directory.rglob("*"), reverse=True):
            if path.is_dir() and not any(path.iterdir()):
                path.rmdir()


def generated_paths(root: Path) -> set[Path]:
    result: set[Path] = set()
    for directory in (
        root / ".codex" / "agents",
        root / ".opencode" / "agents",
        root / ".opencode" / "commands",
        root / ".claude" / "skills",
        root / ".claude" / "agents",
        root / ".agents" / "skills",
    ):
        if not directory.is_dir():
            continue
        for path in directory.rglob("*"):
            if path.is_symlink() or not path.is_file():
                continue
            if MARKER in path.read_text(encoding="utf-8"):
                result.add(path)
    return result


def main() -> int:
    args = parse_args()
    root = find_root(args.root)
    try:
        guidance = discover_guidance(root)
        expected = {
            path: format_content(root, path, content)
            for path, content in provider_files(root, guidance, load_servers(root)).items()
        }
    except (OSError, ValueError, TypeError) as error:
        print(f"Agent configuration error: {error}", file=sys.stderr)
        return 1

    stale = [path for path, content in expected.items() if not path.is_file() or path.read_text(encoding="utf-8") != content]
    orphaned = sorted(generated_paths(root) - set(expected))
    skill_copies = opencode_skill_copies(root)
    tracked_copies = bool(skill_copies) and tracked_in_git(root, ".opencode/skills")
    if args.check:
        if stale or orphaned or tracked_copies:
            print("Agent configuration is out of sync:", file=sys.stderr)
            for path in stale:
                print(f"- stale {path.relative_to(root)}", file=sys.stderr)
            for path in orphaned:
                print(f"- orphaned {path.relative_to(root)}", file=sys.stderr)
            if tracked_copies:
                print(
                    f"- tracked OpenCode skill copies in .opencode/skills ({', '.join(skill_copies)}); "
                    "OpenCode reads .agents/skills, so remove them with `git rm -r .opencode/skills`",
                    file=sys.stderr,
                )
            return 1
        if skill_copies:
            print(
                f"Note: {len(skill_copies)} untracked OpenCode skill copies in .opencode/skills; "
                "`yarn agents:sync` removes them."
            )
    else:
        for path, content in expected.items():
            # A symlinked skill directory would send the generated mirror into .agents/skills itself.
            if path.parent.is_symlink():
                path.parent.unlink()
            elif path.is_symlink():
                path.unlink()
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
        for path in orphaned:
            path.unlink()
        prune_empty_directories(root)
        if skill_copies and not tracked_copies:
            shutil.rmtree(root / ".opencode" / "skills")
            print(f"Removed {len(skill_copies)} OpenCode skill copies recreated by nx configure-ai-agents.")

    package_command = [sys.executable, str(root / ".agents" / "scripts" / "package_skills.py")]
    if args.check:
        package_command.append("--check")
    package_result = subprocess.run(package_command, cwd=root, check=False)
    if package_result.returncode:
        return package_result.returncode
    action = "synchronized" if not args.check else "current"
    print(f"Agent configuration is {action} ({len(guidance)} guidance sources, {len(expected)} generated files).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
