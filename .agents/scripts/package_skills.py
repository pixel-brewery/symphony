#!/usr/bin/env python3
# .agents/scripts/package_skills.py
"""Validate and deterministically package portable repository skills and their Claude Code mirrors."""

from __future__ import annotations

import argparse
import hashlib
import io
import json
import re
import sys
import zipfile
from pathlib import Path

from agent_config_common import find_root as locate_root, parse_frontmatter as read_frontmatter, plugin_provided_skills

GENERATED_MARKER = "Generated by .agents/scripts/sync_agent_configuration.py"
IGNORED_NAMES = {".DS_Store", "__pycache__"}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail when packages or the lock file are stale.")
    parser.add_argument("--root", type=Path, default=None, help="Repository root.")
    return parser.parse_args()


def find_root(explicit: Path | None) -> Path:
    return locate_root(explicit, ".agents/skills")


def parse_frontmatter(text: str, path: Path) -> tuple[dict[str, str], str]:
    metadata, body = read_frontmatter(text)
    if not metadata:
        raise ValueError(f"{path}: invalid or missing YAML frontmatter")
    return metadata, body


def claude_mirror(root: Path, name: str) -> Path:
    return root / ".claude" / "skills" / name / "SKILL.md"


def validate_claude_mirror(root: Path, name: str, metadata: dict[str, str]) -> None:
    mirror = claude_mirror(root, name)
    if not mirror.is_file():
        raise ValueError(f"{mirror.relative_to(root)}: missing Claude Code mirror; run yarn agents:sync")
    text = mirror.read_text(encoding="utf-8")
    if GENERATED_MARKER not in text:
        raise ValueError(f"{mirror.relative_to(root)}: must be generated by sync_agent_configuration.py")
    mirrored, _ = parse_frontmatter(text, mirror)
    if mirrored.get("name") != name or mirrored.get("description") != metadata["description"]:
        raise ValueError(f"{mirror.relative_to(root)}: name or description differs from .agents/skills/{name}/SKILL.md")


def validate_skill(root: Path, skill_dir: Path) -> str:
    skill_file = skill_dir / "SKILL.md"
    text = skill_file.read_text(encoding="utf-8")
    metadata, body = parse_frontmatter(text, skill_file)
    if set(metadata) != {"name", "description"}:
        raise ValueError(f"{skill_file}: frontmatter must contain only name and description")
    name = metadata["name"]
    if name != skill_dir.name or not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", name):
        raise ValueError(f"{skill_file}: name must match its lowercase hyphenated directory")
    if not 1 <= len(name) <= 64 or not 1 <= len(metadata["description"]) <= 1024:
        raise ValueError(f"{skill_file}: name or description length is invalid")
    if "TODO" in body:
        raise ValueError(f"{skill_file}: unresolved TODO")
    openai_file = skill_dir / "agents" / "openai.yaml"
    if not openai_file.is_file():
        raise ValueError(f"{skill_file}: agents/openai.yaml is required")
    openai_text = openai_file.read_text(encoding="utf-8")
    invocation = "$" + name
    if invocation not in openai_text:
        raise ValueError(f"{openai_file}: default_prompt must invoke {invocation}")
    if name not in plugin_provided_skills(root):
        validate_claude_mirror(root, name, metadata)
    return text


def portable_skill_dirs(root: Path) -> list[Path]:
    result: list[Path] = []
    for skill_dir in sorted((root / ".agents" / "skills").iterdir()):
        if not skill_dir.is_dir() or not (skill_dir / "SKILL.md").is_file():
            continue
        text = validate_skill(root, skill_dir)
        if GENERATED_MARKER not in text:
            result.append(skill_dir)
    return result


def archive_bytes(skill_dir: Path) -> bytes:
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
        directory = zipfile.ZipInfo(f"{skill_dir.name}/", date_time=(1980, 1, 1, 0, 0, 0))
        directory.create_system = 3  # Canonical Unix metadata, including on Windows builders.
        directory.external_attr = 0o755 << 16
        archive.writestr(directory, b"")
        # Path comparison is case-insensitive on Windows; archive order must retain POSIX components.
        for path in sorted(skill_dir.rglob("*"), key=lambda path: path.relative_to(skill_dir).parts):
            if path.is_dir() or any(part in IGNORED_NAMES for part in path.parts):
                continue
            relative = path.relative_to(skill_dir).as_posix()
            info = zipfile.ZipInfo(f"{skill_dir.name}/{relative}", date_time=(1980, 1, 1, 0, 0, 0))
            info.create_system = 3
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            archive.writestr(info, path.read_bytes())
    return buffer.getvalue()


def expected_artifacts(root: Path) -> tuple[dict[Path, bytes], str]:
    packages: dict[Path, bytes] = {}
    entries: list[dict[str, str]] = []
    for skill_dir in portable_skill_dirs(root):
        data = archive_bytes(skill_dir)
        archive_path = root / ".agents" / "packages" / f"{skill_dir.name}.skill"
        packages[archive_path] = data
        entries.append(
            {
                "name": skill_dir.name,
                "source": f".agents/skills/{skill_dir.name}",
                "archive": f".agents/packages/{skill_dir.name}.skill",
                "claude": claude_mirror(root, skill_dir.name).relative_to(root).as_posix(),
                "sha256": hashlib.sha256(data).hexdigest(),
            }
        )
    lock = json.dumps({"version": 1, "skills": entries}, indent=2, ensure_ascii=False) + "\n"
    return packages, lock


def main() -> int:
    args = parse_args()
    root = find_root(args.root)
    try:
        packages, lock = expected_artifacts(root)
    except (OSError, ValueError) as error:
        print(f"Skill validation failed: {error}", file=sys.stderr)
        return 1

    package_root = root / ".agents" / "packages"
    lock_path = root / "skills-lock.json"
    stale: list[str] = []
    for path, data in packages.items():
        if not path.is_file() or path.read_bytes() != data:
            stale.append(str(path.relative_to(root)))
    existing = set(package_root.glob("*.skill")) if package_root.is_dir() else set()
    stale.extend(str(path.relative_to(root)) for path in sorted(existing - set(packages)))
    if not lock_path.is_file() or lock_path.read_text(encoding="utf-8") != lock:
        stale.append("skills-lock.json")

    if args.check:
        if stale:
            print("Portable skill artifacts are stale:", file=sys.stderr)
            for path in stale:
                print(f"- {path}", file=sys.stderr)
            return 1
        print(f"Portable skill packages are current ({len(packages)} skills).")
        return 0

    package_root.mkdir(parents=True, exist_ok=True)
    for path in existing - set(packages):
        path.unlink()
    for path, data in packages.items():
        path.write_bytes(data)
    lock_path.write_text(lock, encoding="utf-8")
    print(f"Packaged {len(packages)} portable skills.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
